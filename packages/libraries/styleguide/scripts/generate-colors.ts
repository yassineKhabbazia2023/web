import { writeFileSync } from 'fs'
import { colorsConfig } from '../src/guidelines/Color/colorsConfig'
import { logger } from '@pulse/core'

/*
 Generates ColorName enum and color.variables.ts accordingly to colorsConfig
*/

const DONT_MODIFY = '/* DO NOT MODIFY THIS FILE, IT IS GENERATED BY A SCRIPT */'

const [colorNameFilePath, colorsScssFilePath] = process.argv.slice(2)

const COLOR_KEYWORDS = [
  'color-white',
  'green',
  'orange',
  'primary-color',
  'red',
  'teal',
]

function getAllColors(colorsConfig: Record<string, Record<string, string>>) {
  const allColors = Object
    .keys(colorsConfig)
    .reduce((allColors, groupKey) => {
      Object
        .keys(colorsConfig[groupKey])
        .forEach(key => {
          allColors[`${groupKey}-${key}`] = colorsConfig[groupKey][key]
        })

      return allColors
    }, {})

  logger.info(allColors)

  return Object.keys(allColors)
}

function getFormattedColors(colorsConfig: Record<string, Record<string, string>>) {
  const formattedColorsEmpty: string[] = []
  const formattedColors = Object
    .keys(colorsConfig)
    .reduce((allColors, groupKey) => {
      allColors.push(`  '${groupKey}': (`)
      Object
        .keys(colorsConfig[groupKey])
        .forEach(key => {
          const value = colorsConfig[groupKey][key]
          const colorValue = COLOR_KEYWORDS.includes(value) ? `$${value}` : value
          allColors.push(`    '${key}': ${colorValue},`)
        })

      allColors.push('  ),')

      return allColors
    }, formattedColorsEmpty)

  return formattedColors
}

function writeColorsScss(outputFilePath: string, formattedColors: string[]) {
  const content = `${DONT_MODIFY}\n@use './common-vars' as *;\n\n$colors: (\n${formattedColors.join('\n')}\n);\n`

  writeFileSync(outputFilePath, content, 'utf8')
  logger.info(`✅ ${outputFilePath} successfully generated`)
}

function writeColorName(outputFilePath: string, allColors: string[]) {
  const content = `${DONT_MODIFY}\nexport type ColorName =\n  '${allColors.join("' |\n  '")}'\n`

  writeFileSync(outputFilePath, content, 'utf8')
  logger.info(`✅ ${outputFilePath} successfully generated`)
}

function generateColorName(
  colorsConfig: Record<string, Record<string, string>>,
  colorNameFilePath: string,
  colorsScssFilePath: string,
) {
  const allColors = getAllColors(colorsConfig)
  const formattedColors = getFormattedColors(colorsConfig)

  writeColorName(colorNameFilePath, allColors)
  writeColorsScss(colorsScssFilePath, formattedColors)
}

generateColorName(colorsConfig, colorNameFilePath, colorsScssFilePath)
