/**
 * Generates SCSS color variables in the same format as color.variables.scss
 */
function generateScssColorVariables(colors: Record<string, any>): string {
  let scssContent = ''

  function processObject(obj: Record<string, any>, indentLevel: number = 1): string {
    const indent = '  '.repeat(indentLevel)
    const nextIndent = '  '.repeat(indentLevel + 1)

    let content = '(\n'
    Object.entries(obj).forEach(([key, value]) => {
      content += `${nextIndent}'${key}': `
      if (typeof value === 'string') {
        content += `${value},\n`
      } else if (typeof value === 'object' && value !== null) {
        content += `${processObject(value, indentLevel + 1)},\n`
      }
    })
    content += `${indent})`
    return content
  }

  scssContent += '$colors: (\n'

  Object.entries(colors).forEach(([colorName, colorValue]) => {
    scssContent += `  '${colorName}': `
    if (typeof colorValue === 'string') {
      scssContent += `${colorValue},\n`
    } else if (typeof colorValue === 'object' && colorValue !== null) {
      scssContent += `${processObject(colorValue, 1)},\n`
    }
  })

  scssContent += ');\n'
  return scssContent
}

/**
 * Generates the color.variables.scss file with pegaseColors and figmaProxyTokens
 */
function generatePegaseColorVariables(): void {
  const outputPath = resolve(__dirname, '../src/assets/scss/pegase/color.variables.scss')

  logger.info('🎨 Generating Pégase color variables SCSS file...')

  const allColors = { ...pegaseColors, ...figmaProxyTokens }
  const colorVariables = generateScssColorVariables(allColors)

  const scssContent = `/* DO NOT MODIFY THIS FILE, IT IS GENERATED BY A SCRIPT */

${colorVariables}
`

  try {
    writeFileSync(outputPath, scssContent, 'utf8')
    logger.info(`✅ Color variables SCSS file generated successfully: ${outputPath}`)

    // Count generated color groups
    const colorGroupCount = Object.keys(allColors).length
    logger.info(`📊 Color groups generated: ${colorGroupCount} color groups`)
  } catch (error) {
    logger.error('❌ Error generating color variables SCSS file:', error)
    throw error
  }
}

